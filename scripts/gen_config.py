def rows(data, name):
    with open(os.path.join(data, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def dump(obj):
    return HEADER + yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=120, allow_unicode=True)


def good(name):
    return bool(name) and name != "invalid" and not name.isdigit() and "not_used" not in name and not name.startswith("_Z") \
        and "+" not in name and not name.startswith("dedicated_")


AUTOFIRE_SW = {"left_slingshot", "right_slingshot", "left_pop_bumper", "right_pop_bumper", "bottom_pop_bumper",
                "lock_1", "lock_2", "lock_3", "elevator_popper", "throne", "shooter_lane"}


def switches(data):
    out = {}
    nonpf = {15, 16, 17, 18, 19, 20, 21, 22, 23, 27, 45, 55}      # trough, start buttons, topper, dragon home
    for r in rows(data, "switches.csv"):
        n = int(r["sw_id"])
        if not good(r["name"]):
            continue
        sw = {"number": "S%d" % n, "label": r["label_en"].title() if r["label_en"] else r["name"]}
        tags = []
        if n == 45:
            tags.append("start")
        if n not in nonpf and r["name"] not in AUTOFIRE_SW:   # autofire devices tag these themselves
            tags.append("playfield_active")
        if tags:
            sw["tags"] = ", ".join(tags)
        out["s_" + r["name"]] = sw
    for r in rows(data, "switches_dedicated.csv"):
        if good(r["name"]):
            out["s_" + r["name"]] = {"number": "D%s" % r["idx"], "label": r["label_en"].title()}
    for name in ("service_back", "service_minus", "service_plus", "service_select"):
        out["s_" + name]["tags"] = "service"
    out["s_tilt_pendulum"]["tags"] = "tilt_warning"
    out["s_slam_tilt"]["tags"] = "slam_tilt"
    out["s_left_coin"]["tags"] = "left_coin"
    out["s_center_coin"]["tags"] = "center_coin"
    out["s_right_coin"]["tags"] = "right_coin"
    return {"switches": out}


def coils(data):
    """Pulse times from data/coil_timing.csv (extraction of the ROM's call sites and coil table): the game's own pulse when a call
    site gives one (H), else the coil table default (64 ms); slings 16 ms and pops 32 ms are the node reflex values (M); flippers
    40 ms initial pulse with hold level 32/255 (node reflex)."""
    out = {}
    timing = {r["coil_id"]: r for r in rows(data, "coil_timing.csv")} if os.path.exists(os.path.join(data, "coil_timing.csv")) else {}
    for r in rows(data, "coils.csv"):
        if good(r["name"]):
            n = r["name"]
            t = timing.get(r["coil_id"], {})
            ms = 25                                              # CFG when the timing table is absent
            if t:
                g, d = (t.get("game_pulse_ms") or "").strip(), (t.get("default_pulse_ms") or "").strip()
                m = re.match(r"\d+", g)
                ms = int(m.group()) if m else int(d) if d.isdigit() and int(d) else 64
            out["c_" + n] = {"number": "C%s" % r["coil_id"], "label": r["label_en"].title(), "default_pulse_ms": ms}
    for n, ms in (("left_slingshot", 16), ("right_slingshot", 16), ("left_pop_bumper", 32), ("right_pop_bumper", 32),
                  ("bottom_pop_bumper", 32)):
        out["c_" + n]["default_pulse_ms"] = ms
    for f in ("left_flipper_power", "right_flipper_power", "u_p_left_flipper", "u_p_right_flipper"):
        out["c_" + f]["default_pulse_ms"] = 40
        out["c_" + f]["default_hold_power"] = round(32 / 255, 3)      # flipper node reflex: hold level 32 of 255
    out["c_shaker_motor"]["default_pulse_ms"] = 100                  # table 1000 ms; MPF pulses are short, the shaker is held by a show
    return {"coils": out}


def lights(data):
    """The ROM's 101 named light groups (data/lights.csv: type 1 flasher/button, 2 lamp, 3 GI, 4 backbox GI).
    Tags group them for the light shows (game/config/lightshow.yaml): gi, flasher, lamp, sigil, house_<key>, arrow."""
    out = {}
    houses = ("targaryen", "stark", "baratheon", "lannister", "greyjoy", "tyrell", "martell")
    for r in rows(data, "lights.csv"):
        n = r["name"]
        if n == "lt_invalid":
            continue
        n = n[3:] if n.startswith("lt_") else n
        tags = {"1": ["flasher"], "2": ["lamp"], "3": ["gi"], "4": ["gi"]}[r["type"]]
        if n.endswith("_sigil"):
            tags.append("sigil")
            for h in houses:
                if h in n:
                    tags.append("house_" + h)
        if "arrow" in n:
            tags.append("arrow")
        if n.startswith("fl_") or n.startswith("topper_dragon_flasher"):
            tags.append("flashfx")
        out["l_" + n] = {"number": "L%s" % r["light_id"], "label": n.replace("_", " ").title(), "tags": ", ".join(tags)}
    return {"lights": out}


def signed(v):
    v = int(v)
    return v - (1 << 32) if v >= (1 << 31) else v


def settings(data):
    out = {}
    for r in rows(data, "adjustments.csv"):
        if r["name"] == "ad_invalid":
            continue
        lo, hi, step, dflt = signed(r["min"]), signed(r["max"]), max(int(r["step"]), 1), signed(r["default"])
        vals = list(range(lo, hi + 1, step))
        if len(vals) > 40:                       # keep the menu usable: ~30 evenly spaced values plus the default
            keep = {vals[i * (len(vals) - 1) // 29] for i in range(30)} | {dflt}
            vals = sorted(keep)
        if dflt not in vals:
            vals = sorted(set(vals) | {dflt})
        labels = {0: "NO", 1: "YES"} if r["format"] == "adtml_no_yes" else {}
        out[r["name"]] = {"label": r["label_en"], "default": dflt, "key_type": "int", "sort": int(r["index"]),
                          "values": {v: labels.get(v, "{:,}".format(v)) + (" (default)" if v == dflt else "") for v in vals}}
    return {"settings": out}


def sounds(data, rules):
    """Core sound set only. The WAVs are copied by scripts/gen_media.py into game/sounds/<track>/ (gitignored)."""
    fx = {r["name"]: r for r in rows(data, "sound_effects.csv")}
    cat = {int(r["sound_id"]): r for r in rows(data, "audio_catalog.csv")}
    # GMC 1.0 (MPF 0.80) has no `sounds:`/`sound_pools:` section: it registers every file of game/sounds/<track>/ by
    # its file stem. A pooled effect plays its first sound (GMC has no random_force_next pool; CFG: lost variety).
    player, files = {}, {}
    for event, se in rules["sounds"].items():
        r = fx[se]
        i = int(r["sound_ids"].split()[0])
        c = cat[i]
        track = TRACK.get(c["category"], "sfx")
        stem = os.path.splitext(c["file"])[0]
        files[stem] = {"file": stem + ".ogg", "src": c["file"], "track": track}
        act = {"action": "play", "bus": track}
        if track == "music":
            act["loops"] = -1
        player["got_sound_" + event] = {stem: act}
    sounds.files = files
    return {"sound_player": player}


def all_sounds(data, rules):
    """Every sound effect of data/sound_effects.csv (463) as event got_se_<name>; effects with several variants pick one at random
    (random_event_player). Files are converted to OGG by gen_media.py. Which rule plays which effect is wired in rules.yaml `sounds`."""
    cat = {int(r["sound_id"]): r for r in rows(data, "audio_catalog.csv")}
    player, rnd = {}, {}
    for r in rows(data, "sound_effects.csv"):
        if r["name"] == "se_invalid" or not r["sound_ids"].strip():
            continue
        ids = [int(i) for i in r["sound_ids"].split() if int(i) in cat]
        if not ids:
            continue
        ev = "got_se_" + r["name"][3:]
        names = []
        for k, i in enumerate(ids):
            c = cat[i]
            track = TRACK.get(c["category"], "sfx")
            stem = os.path.splitext(c["file"])[0]
            sounds.files[stem] = {"file": stem + ".ogg", "src": c["file"], "track": track}
            e = ev if len(ids) == 1 else "%s_v%d" % (ev, k + 1)
            act = {"action": "play", "bus": track}
            if "__tune__" in stem:
                act["loops"] = -1                # ROM tunes loop until another tune replaces them (solo music bus)
            player[e] = {stem: act}
            names.append(e)
        if len(ids) > 1:
            rnd[ev] = names               # one variant at random: got.scoreboard (random_event_player is game-mode only)
    all_sounds.variants = rnd
    return {"sound_player": player}


