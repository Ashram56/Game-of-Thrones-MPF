def caller_events(data):
    """event -> [def names] from data/def_callers.csv and CALLER_EVENT. A (award, complete) pair routes the *_complete defs to the
    completion event and the other defs to the award event."""
    path = os.path.join(data, "def_callers.csv")
    out = {}
    if not os.path.exists(path):
        return out
    for r in rows(data, "def_callers.csv"):
        ev = CALLER_EVENT.get(r["caller_function"])
        if not ev or r["event"].startswith("no direct"):
            continue
        d = r["def_name"]
        if isinstance(ev, tuple):
            ev = ev[1] if d.endswith("_complete") else ev[0]
        if ev:
            out.setdefault(ev, [])
            if d not in out[ev]:
                out[ev].append(d)
    return out


def triggers(data, rules):
    """Wire the ROM's display effects: event got_def_<name> posts the effect's sounds (got_se_*) and plays its DMD clip."""
    rows_ = rows(data, "triggers_sound_video.csv")
    vids = {int(r["video_id"]): int(r["frames"]) for r in rows(data, "dmd_videos.csv")}
    fps = float(rules["dmd"]["fps"])
    sfx, vid, first = {}, {}, {}
    for r in rows_:
        t, kind, ident = r["trigger"], r["kind"], r["id_or_name"]
        if kind == "sound" and ident.startswith("se_"):
            first.setdefault(t, [])
            ev = "got_se_" + ident[3:]
            if ev not in first[t]:
                first[t].append(ev)
        elif kind == "video" and ident.lstrip("-").isdigit():
            vid.setdefault(t, int(ident))
    player, slides_ = {}, {}
    for t, evs in first.items():
        if t.startswith("def_"):
            player["got_def_" + t[4:]] = evs
    for t, v in vid.items():
        if t.startswith("def_") and v in vids:
            slides_["got_def_" + t[4:]] = {"vid%03d" % v: {"expire": "%.1fs" % (max(1, vids[v]) / fps + 0.5)}}
    # lamp effects: a def_* requests lef_* effects (data/triggers_lamp_coil.csv); a lef's lights come from the same file (H light ids)
    lamp = rows(data, "triggers_lamp_coil.csv") if os.path.exists(os.path.join(data, "triggers_lamp_coil.csv")) else []
    lef_lights = {}
    shows_csv = os.path.join(data, "light_shows.csv")
    show_type = {}
    if os.path.exists(shows_csv):
        for r in rows(data, "light_shows.csv"):                 # 133 lamp effects with the lights each touches (H)
            show_type[r["name"]] = r["type_meaning"]
            for lt in r["lights"].split():
                if lt.startswith("lt_"):
                    lef_lights.setdefault(r["name"], [])
                    if "l_" + lt[3:] not in lef_lights[r["name"]]:
                        lef_lights[r["name"]].append("l_" + lt[3:])
    for r in lamp:
        if r["kind"] == "light" and r["id_or_name"].startswith("lt_") and r["rule_function"].startswith("lef_"):
            lef_lights.setdefault(r["rule_function"], [])
            if "l_" + r["id_or_name"][3:] not in lef_lights[r["rule_function"]]:
                lef_lights[r["rule_function"]].append("l_" + r["id_or_name"][3:])
    for r in lamp:
        if r["kind"] == "lef" and r["rule_function"].startswith("def_") and r["id_or_name"] in lef_lights \
                and not r["id_or_name"].endswith("_background"):
            ev = "got_" + r["id_or_name"]
            lst = player.setdefault("got_def_" + r["rule_function"][4:], [])
            if ev not in lst:
                lst.append(ev)
    triggers.lef_shows = {k: v for k, v in lef_lights.items() if not k.endswith("_background") and "background" not in show_type.get(k, "")}
    for h, d in HOUSE_DEF.items():
        player["mode_%s_started" % h] = ["got_def_" + d[4:]]
    for ev, d in EVENT_DEF.items():
        player[ev] = ["got_def_" + d[4:]]
    for ev, defs in caller_events(data).items():            # the ROM's own callers (def_callers.csv) win over the table above
        player[ev] = ["got_def_" + d[4:] for d in defs]
    for t, sw in SWITCH_TRIGGER.items():
        if first.get(t):
            player[sw + "_active"] = [first[t][0]]
    # a def with a clip but no sound still needs its event
    for k in slides_:
        player.setdefault(k, [])
    player = {k: v for k, v in player.items() if v or k.startswith("got_def_")}
    for k in [k for k, v in player.items() if not v]:
        del player[k]
    shows, show_player = {}, {}
    for name, lights_ in sorted(triggers.lef_shows.items()):
        shows[name] = [{"time": 0, "lights": {l: "ffffff" for l in lights_}}, {"time": 0.4, "lights": {l: "000000" for l in lights_}},
                       {"time": 0.6, "lights": {l: "ffffff" for l in lights_}}, {"time": 1.0, "lights": {l: "000000" for l in lights_}},
                       {"time": 1.2}]
        show_player["got_" + name] = {name: {"loops": 0, "key": name}}
    for ev, v in text_slides(data)[1].items():
        slides_.setdefault(ev, v)                                      # a def with a clip keeps its clip
    return {"event_player": player, "slide_player": slides_, "shows": shows, "show_player": show_player}


def build(data):
    with open(os.path.join(GAME, "config", "rules.yaml"), encoding="utf-8") as f:
        rules = yaml.safe_load(f)
    rules = apply_scoring(rules, data)
    files = {}
    for name, fn in (("switches", switches), ("coils", coils), ("lights", lights), ("settings", settings)):
        files["config/rom/%s.yaml" % name] = dump(fn(data))
    sc = {"mode": {"start_events": "ball_starting", "stop_events": "ball_ending", "priority": 90, "game_mode": True}}
    sc.update(switch_scores(data, rules))
    sc["mode_settings"] = {"bonus_hit_switches": sorted(switch_scores.bonus_hits)}
    files["config/rom/pop_awards.json"] = json.dumps(
        [{"id": int(r["symbol_id"]), "award": r["award"], "tape": int(r["tape_count_of_112"])} for r in rows(data, "pop_awards.csv")],
        indent=1) + "\n"                                   # Pict-O-Pops awards and tape frequency (docs/09)
    files["modes/scoring/config/scoring.yaml"] = dump(sc)       # variable_player is only valid inside a game mode
    files["config/rom/lightshow.yaml"] = dump(lightshow(rules, data))
    files["config/rom/sounds.yaml"] = dump(sounds(data, rules))
    files["config/rom/defs.yaml"] = dump(triggers(data, rules))
    files["config/rom/sounds_all.yaml"] = dump(all_sounds(data, rules))
    files["config/rom/sound_variants.json"] = json.dumps(all_sounds.variants, indent=1, sort_keys=True) + "\n"
    menu = [r for r in rows(data, "audits_units.csv") if r.get("display_index")]
    menu.sort(key=lambda r: int(r["display_index"]))
    files["config/rom/audit_menu.json"] = json.dumps(
        [{"name": r["name"], "label": r["display_label"], "pct": "% of total plays" in r["unit"],
         "fmt": "time" if r["unit"] == "seconds" else "ticks" if r["unit"].startswith("ticks") else "count"} for r in menu], indent=1) + "\n"
    files["config/rom/audit_labels.json"] = json.dumps(
        {r["name"]: r["decoded_meaning"] for r in rows(data, "audits_meaning.csv") if r["name"] != "au_invalid"}, indent=1, sort_keys=True) + "\n"
    files["config/rom/vm_sprites.json"] = json.dumps(vm_sprites(data), indent=1, sort_keys=True) + "\n"
    files["slides/videomode.tscn"] = VM_TSCN
    files["config/rom/sound_files.json"] = json.dumps(sounds.files, indent=1, sort_keys=True) + "\n"
    files["config/rom/mystery_awards.csv"] = open(os.path.join(data, "mystery_awards.csv")).read()
    files["config/rom/swords.csv"] = open(os.path.join(data, "swords.csv")).read()
    files["config/rom/slides.yaml"] = dump(slides(data, rules))
    files.update(slide_scenes(rules, data))
    files.update(text_slides(data)[0])
    for rel, cfg in mode_files(rules).items():
        files["modes/" + rel] = dump(cfg)
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.environ.get("GOT_DATA", os.path.join(ROOT, "..", "Game-of-Thrones", "data")))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files, bad = build(a.data), []
    for rel, text in files.items():
        path = os.path.join(GAME, rel)
        if a.check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                bad.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    if bad:
        print("out of date:", *bad, sep="\n  ")
        sys.exit(1)
    print(("checked" if a.check else "wrote"), len(files), "files")


if __name__ == "__main__":
    main()
