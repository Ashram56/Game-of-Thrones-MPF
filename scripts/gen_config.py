def lightshow(rules, data=None):
    """Attract light show, GI, flasher pulses: the ROM's lamp/flasher effects (lef_*) are not decoded for Spike 1, so the
    choreography is CFG (sigils sweep in house colours, arrows chase); which light is lit when follows the rules (got/lightshow.py)."""
    keys = [h["key"] for h in rules["houses"] if h["key"] in HOUSE_COLORS]
    off = {"house_" + k: "000000" for k in keys}
    sweep = []
    for i, k in enumerate(keys):
        step = {"time": i * 0.5, "lights": dict(off, **{"house_" + k: HOUSE_COLORS[k]})}
        step["lights"]["arrow"] = "ffffff" if i % 2 == 0 else "000000"
        sweep.append(step)
    sweep.append({"time": len(keys) * 0.5})
    chase = []
    csv_path = os.path.join(data, "light_shows.csv") if data else ""
    if csv_path and os.path.exists(csv_path):                       # lef_attract_mode_background touches these lights (H); chase them
        for r in rows(data, "light_shows.csv"):
            if r["name"] == "lef_attract_mode_background":
                chase = ["l_" + x[3:] for x in r["lights"].split() if x.startswith("lt_") and "gi" not in x and "flasher" not in x]
    out = {
        "shows": {
            "attract_sweep": sweep,
            "pulse": [{"time": 0, "lights": {"(lights)": "ffffff"}}, {"time": "+0.12", "lights": {"(lights)": "000000"}},
                      {"time": "+0.05"}],
        },
        "show_player": {
            "mode_attract_started": {"attract_sweep": {"loops": -1, "key": "attract_sweep"}},
            "mode_attract_stopped": {"attract_sweep": {"action": "stop", "key": "attract_sweep"}},
        },
        "light_player": {
            "init_done": {"gi": "ffffff"},
            "mode_attract_started": {"l_start_button": "ffffff"},
            "ball_starting": {"gi": "ffffff"},
            "tilt": {"gi": "000000"},
            "game_ended": {"lamp": "000000", "flashfx": "000000"},
        },
    }
    if chase:
        out["shows"]["attract_chase"] = [{"time": round(i * 0.1, 1), "lights": {chase[i]: "ffa000", chase[i - 1]: "000000"}} for i in range(len(chase))] \
            + [{"time": round(len(chase) * 0.1, 1), "lights": {chase[-1]: "000000"}}]
        out["show_player"]["mode_attract_started"]["attract_chase"] = {"loops": -1, "key": "attract_chase"}
        out["show_player"]["mode_attract_stopped"]["attract_chase"] = {"action": "stop", "key": "attract_chase"}
    for sw, fx in FLASH_FX.items():
        out["show_player"][sw + "_active"] = {"pulse": {"show_tokens": {"lights": "l_" + fx}, "key": "fx_" + fx, "loops": 0}}
    iron_lamps(out, data)
    hand_lamps(out, data)
    return out


TICK = 1 / 62.0                                       # the ROM's lamp effects run at 62 Hz


def hand_lamps(out, data):
    """Hand of the King lamp effect 110 (start): the lower/left/upper-right/backbox GI flash 6 x (5 ticks on / 5 off), then 4 pulses of 15/15
    (data/chand_lamps.csv, M timing); effects 111 (background blink) and the ready/post-hand chases are driven by got.hand / got.lightshow."""
    if not data or not os.path.exists(os.path.join(data, "chand_lamps.csv")):
        return
    gi = sorted({"l_" + r["lamp_name"][3:] for r in rows(data, "chand_lamps.csv") if r["effect"].startswith("110")})
    if not gi:
        return
    steps, t = [], 0.0
    for on, off in [(5, 5)] * 6 + [(15, 15)] * 4:
        steps.append({"time": round(t, 4), "lights": {x: "ffffff" for x in gi}})
        steps.append({"time": round(t + on * TICK, 4), "lights": {x: "000000" for x in gi}})
        t += (on + off) * TICK
    steps.append({"time": round(t, 4)})
    out["shows"]["hand_start"] = steps
    a_lamps = sorted({"l_" + r["lamp_name"][3:] for r in rows(data, "chand_lamps.csv") if r["effect"].startswith("124") and r["lamp_name"].startswith("lt_")
                      and r["state"].startswith("white")})
    b_lamps = sorted({"l_" + r["lamp_name"][3:] for r in rows(data, "chand_lamps.csv") if r["effect"].startswith("124") and r["lamp_name"].startswith("lt_")
                      and r["state"].startswith("off in phase A")})
    if a_lamps and b_lamps:                 # effect 124 (every Hand payment): phases A / B of 4 ticks, four cycles, then a 4 tick blackout (M)
        fr = []
        for c in range(4):
            fr.append({"time": round(c * 8 * TICK, 4), "lights": dict({x: "ffffff" for x in a_lamps}, **{x: "000000" for x in b_lamps})})
            fr.append({"time": round((c * 8 + 4) * TICK, 4), "lights": dict({x: "000000" for x in a_lamps}, **{x: "ffffff" for x in b_lamps})})
        fr.append({"time": round(32 * TICK, 4), "lights": {x: "000000" for x in a_lamps + b_lamps}})
        fr.append({"time": round(36 * TICK, 4)})
        out["shows"]["hand_award"] = fr
        for ev in ("got_hand_of_the_king_award", "got_hand_of_the_king_super", "got_hand_hurry_up"):
            out["show_player"][ev] = {"hand_award": {"loops": 0, "key": "hand_award"}}
    chase = [("l_" + r["lamp_name"][3:]) for r in rows(data, "chand_lamps.csv") if r["effect"].startswith("109")]
    if chase:             # effect 109 (ready): hand lamp, ramp bottom arrow, lock, sigil, top arrow lit in sequence (steps 4,4,4,2,2 ticks), held 4, off 8 (M reading)
        frames, t = [], 0.0
        for n, d in enumerate((4, 4, 4, 2, 2)):
            frames.append({"time": round(t, 4), "lights": {x: ("ffffff" if i <= n else "000000") for i, x in enumerate(chase)}})
            t += d * TICK
        frames.append({"time": round(t, 4), "lights": {x: "ffffff" for x in chase}})
        t += 4 * TICK
        frames.append({"time": round(t, 4), "lights": {x: "000000" for x in chase}})
        t += 8 * TICK
        frames.append({"time": round(t, 4)})
        out["shows"]["hand_ready"] = frames
        out["show_player"]["got_hand_ready_lamps"] = {"hand_ready": {"loops": -1, "key": "hand_ready"}}
        out["show_player"]["got_hand_ready_lamps_off"] = {"hand_ready": {"action": "stop", "key": "hand_ready"}}
    out["show_player"]["mode_hand_of_the_king_started"] = {"hand_start": {"loops": 0, "key": "hand_start"}}


def iron_lamps(out, data):
    """Iron Throne lamp effects 89 (start), 91 (castle pick / state-1 shot), 92 (ram): data/ciron_lamps.csv (H strings and ticks, M timing)."""
    if not data or not os.path.exists(os.path.join(data, "ciron_lamps.csv")):
        return
    comet, flash91, flash92, blip = {}, [], [], []
    for r in rows(data, "ciron_lamps.csv"):
        eff, lamp = r["effect"].split()[0], "l_" + r["lamp_name"][3:]
        m = re.search(r"string position (\d+)", r["state"])
        if eff in ("89", "92") and m:
            comet.setdefault(eff, {})[int(m.group(1))] = lamp
        elif eff == "91" and "blip" in r["state"]:
            blip.append(lamp)
        elif eff in ("91", "92") and "flashing" in r["state"]:
            (flash91 if eff == "91" else flash92).append(lamp)
    if not comet.get("89") or not comet.get("92"):
        return

    def comet_show(order, step_s, black_fill):
        n, tail, steps, t = len(order), 10, [], 0.0
        path = [(h, 1) for h in range(n + tail)] + [(h, -1) for h in range(n - 1, -tail - 1, -1)]     # up, then back down
        for head, sign in path:
            lights = {}
            for i, lamp in enumerate(order):
                d = (head - i) * sign
                level = (tail + 1 - d) / (tail + 1) if 0 <= d <= tail else 0
                if level > 0:
                    g = "%02x" % int(255 * level)
                    lights[lamp] = g * 3
                elif black_fill:
                    lights[lamp] = "000000"
            steps.append({"time": round(t, 4), "lights": lights})
            t += step_s
        steps.append({"time": round(t, 4), "lights": {lamp: "000000" for lamp in order} if black_fill else {}})
        return steps

    def flash_show(lamps, n_flash, half_s, lead=None):
        steps, t = [], 0.0
        if lead:
            steps.append({"time": 0, "lights": {x: "ffffff" for x in lead}})
            t = TICK
        for i in range(n_flash):
            steps.append({"time": round(t, 4), "lights": {x: "ffffff" for x in lamps}})
            steps.append({"time": round(t + half_s, 4), "lights": {x: "000000" for x in lamps}})
            t += 2 * half_s
        steps.append({"time": round(t, 4)})
        return steps

    o89 = [comet["89"][i] for i in sorted(comet["89"])]
    o92 = [comet["92"][i] for i in sorted(comet["92"])]
    out["shows"]["iron_start"] = comet_show(o89, 3 * TICK, True)
    out["shows"]["iron_award"] = flash_show(flash91, 10, 4 * TICK, blip)
    sj = comet_show(o92, TICK, False)
    end = sj[-1]["time"]
    out["shows"]["iron_super"] = sj[:-1] + [dict(st, time=round(st["time"] + end, 4)) for st in flash_show(flash92, 15, 4 * TICK)]
    sp = out["show_player"]
    sp["mode_iron_throne_started"] = {"iron_start": {"loops": 0, "key": "iron_start"}}
    sp["got_iron_award"] = {"iron_award": {"loops": 0, "key": "iron_award"}}
    sp["got_iron_super_lamps"] = {"iron_super": {"loops": 0, "key": "iron_super"}}


