#!/usr/bin/env python3
"""Generate MPF config from the extraction data (Game-of-Thrones data/*.csv) and game/config/rules.yaml.

  python scripts/gen_config.py [--data DIR] [--check]

Writes game/config/rom/{switches,coils,lights,settings,sounds,slides}.yaml and game/modes/<key>/config/<key>.yaml.
--check regenerates in memory and fails when a committed file differs (used by tests). The data directory is the
Game-of-Thrones repo's data/ (env GOT_DATA, default ../Game-of-Thrones/data); nothing is read from the ROM.
"""
import argparse
import csv
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "game")
HEADER = "#config_version=6\n# GENERATED by scripts/gen_config.py - do not edit; change rules.yaml or the data tables.\n"
TRACK = {"tune": "music", "vo": "voice"}


def rows(data, name):
    with open(os.path.join(data, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def dump(obj):
    return HEADER + yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=120, allow_unicode=True)


def good(name):
    return bool(name) and name != "invalid" and not name.isdigit() and "not_used" not in name and not name.startswith("_Z") \
        and "+" not in name and not name.startswith("dedicated_")


AUTOFIRE_SW = {"left_slingshot", "right_slingshot", "left_pop_bumper", "right_pop_bumper", "bottom_pop_bumper",
                "lock_1", "lock_2", "lock_3", "elevator_popper", "throne", "shooter_lane"}


def switches(data):
    out = {}
    nonpf = {15, 16, 17, 18, 19, 20, 21, 22, 23, 27, 45, 55}      # trough, start buttons, topper, dragon home
    for r in rows(data, "switches.csv"):
        n = int(r["sw_id"])
        if not good(r["name"]):
            continue
        sw = {"number": "S%d" % n, "label": r["label_en"].title() if r["label_en"] else r["name"]}
        tags = []
        if n == 45:
            tags.append("start")
        if n not in nonpf and r["name"] not in AUTOFIRE_SW:   # autofire devices tag these themselves
            tags.append("playfield_active")
        if tags:
            sw["tags"] = ", ".join(tags)
        out["s_" + r["name"]] = sw
    for r in rows(data, "switches_dedicated.csv"):
        if good(r["name"]):
            out["s_" + r["name"]] = {"number": "D%s" % r["idx"], "label": r["label_en"].title()}
    for name in ("service_back", "service_minus", "service_plus", "service_select"):
        out["s_" + name]["tags"] = "service"
    out["s_tilt_pendulum"]["tags"] = "tilt_warning"
    out["s_slam_tilt"]["tags"] = "slam_tilt"
    out["s_left_coin"]["tags"] = "left_coin"
    out["s_center_coin"]["tags"] = "center_coin"
    out["s_right_coin"]["tags"] = "right_coin"
    return {"switches": out}


def coils(data):
    out = {}
    for r in rows(data, "coils.csv"):
        if good(r["name"]):
            n = r["name"]
            out["c_" + n] = {"number": "C%s" % r["coil_id"], "label": r["label_en"].title(),
                             "default_pulse_ms": 25}      # CFG: Spike 1 coil timing not extracted (flags column is raw)
    out["c_shaker_motor"]["default_pulse_ms"] = 100
    return {"coils": out}


def lights(data):
    out = {}
    for r in rows(data, "lamps.csv"):
        n = r["name"]
        if n == "invalid":
            continue
        name = "l_lamp_%s" % n if n.isdigit() else "l_" + n
        out[name] = {"number": "L%s" % r["lamp_id"], "label": r["label_en"].title()}
    return {"lights": out}


def signed(v):
    v = int(v)
    return v - (1 << 32) if v >= (1 << 31) else v


def settings(data):
    out = {}
    for r in rows(data, "adjustments.csv"):
        if r["name"] == "ad_invalid":
            continue
        lo, hi, step, dflt = signed(r["min"]), signed(r["max"]), max(int(r["step"]), 1), signed(r["default"])
        vals = list(range(lo, hi + 1, step))
        if len(vals) > 40:                       # keep the menu usable: ~30 evenly spaced values plus the default
            keep = {vals[i * (len(vals) - 1) // 29] for i in range(30)} | {dflt}
            vals = sorted(keep)
        if dflt not in vals:
            vals = sorted(set(vals) | {dflt})
        labels = {0: "NO", 1: "YES"} if r["format"] == "adtml_no_yes" else {}
        out[r["name"]] = {"label": r["label_en"], "default": dflt, "key_type": "int", "sort": int(r["index"]),
                          "values": {v: labels.get(v, "{:,}".format(v)) + (" (default)" if v == dflt else "") for v in vals}}
    return {"settings": out}


def sounds(data, rules):
    """Core sound set only. The WAVs are copied by scripts/gen_media.py into game/sounds/<track>/ (gitignored)."""
    fx = {r["name"]: r for r in rows(data, "sound_effects.csv")}
    cat = {int(r["sound_id"]): r for r in rows(data, "audio_catalog.csv")}
    snd, pools, player = {}, {}, {}
    for event, se in rules["sounds"].items():
        r = fx[se]
        ids = [int(x) for x in r["sound_ids"].split()]
        names = []
        for i in ids:
            c = cat[i]
            track = TRACK.get(c["category"], "sfx")
            name = "snd%04d" % i
            snd[name] = {"file": c["file"], "track": track}
            if track == "music":
                snd[name]["loops"] = -1
            names.append(name)
        if len(names) == 1:
            target = names[0]
        else:
            target = se
            pools[se] = {"type": "random_force_next", "track": snd[names[0]]["track"], "sounds": ", ".join(names)}
        player["got_sound_" + event] = {target: {"action": "play"}}
    out = {"sounds": snd}
    if pools:
        out["sound_pools"] = pools
    out["sound_player"] = player
    return out


def slides(data, rules):
    vids = {int(r["video_id"]): r for r in rows(data, "dmd_videos.csv")}
    out_slides, player = {}, {}
    for event, vid in rules["dmd"]["videos"].items():
        v = vids[int(vid)]
        sname = "vid%03d" % vid
        out_slides[sname] = {"widgets": [{"type": "image", "image": "dmd_vid%03d_f000" % vid}]}
        player[event] = {sname: {"expire": "2s"}}
    return {"slides": out_slides, "slide_player": player}


def mode_files(rules):
    out = {}
    d = rules["defaults"]
    for h in rules["houses"]:
        key = h["key"]
        award = {k: h["award"].get(k, 0) for k in ("start", "bump", "cap")}
        cfg = {"mode": {"start_events": "start_mode_" + key, "stop_events": "stop_mode_%s, ball_ending, tilt" % key,
                        "priority": 300, "game_mode": True, "code": "got.award_mode.AwardMode"},
               "mode_settings": {"kind": "house", "id": h["id"], "key": key, "award": award, "shots": h["shots"],
                                 "shots_to_complete": d["house_shots_to_complete"], "hurry_up": bool(h.get("hurry_up")),
                                 "confidence": {"timer": h["timer_conf"], "award": h["award"]["conf"]}},
               "timers": {key + "_timer": {"start_value": h["timer_s"], "end_value": 0, "direction": "down",
                                           "tick_interval": "1s", "start_running": True}},
               "event_player": {"timer_%s_timer_complete" % key: "stop_mode_" + key}}
        out["%s/config/%s.yaml" % (key, key)] = cfg
    for m in rules["multiballs"]:
        key = m["key"]
        a = {k: m["jackpot"].get(k, 0) for k in ("start", "bump", "cap")}
        cfg = {"mode": {"start_events": "start_mode_" + key, "stop_events": "stop_mode_%s, multiball_%s_ended, tilt" % (key, key),
                        "priority": 400, "game_mode": True, "code": "got.award_mode.AwardMode"},
               "mode_settings": {"kind": "multiball", "id": m["id"], "key": key, "award": a, "shots": m["jackpot_switches"],
                                 "shots_to_complete": 0, "start_bonus": m["start_bonus"], "flag": m["flag"],
                                 "ball_save_adjustment": m["ball_save_adjustment"],
                                 "confidence": {"award": m["jackpot"]["conf"]}},
               "multiballs": {"mb_" + key: {"ball_count": d["multiball_balls"], "ball_count_type": "total",
                                           "shoot_again": "%ds" % m["ball_save_s"],
                                           "start_events": "mode_%s_started" % key}},
               "variable_player": {"mode_%s_started" % key: {"score": m["start_bonus"]}}}
        out["%s/config/%s.yaml" % (key, key)] = cfg
    return out


def build(data):
    with open(os.path.join(GAME, "config", "rules.yaml"), encoding="utf-8") as f:
        rules = yaml.safe_load(f)
    files = {}
    for name, fn in (("switches", switches), ("coils", coils), ("lights", lights), ("settings", settings)):
        files["config/rom/%s.yaml" % name] = dump(fn(data))
    files["config/rom/sounds.yaml"] = dump(sounds(data, rules))
    files["config/rom/slides.yaml"] = dump(slides(data, rules))
    for rel, cfg in mode_files(rules).items():
        files["modes/" + rel] = dump(cfg)
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.environ.get("GOT_DATA", os.path.join(ROOT, "..", "Game-of-Thrones", "data")))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files, bad = build(a.data), []
    for rel, text in files.items():
        path = os.path.join(GAME, rel)
        if a.check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                bad.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    if bad:
        print("out of date:", *bad, sep="\n  ")
        sys.exit(1)
    print(("checked" if a.check else "wrote"), len(files), "files")


if __name__ == "__main__":
    main()
