#!/usr/bin/env python3
"""Generate MPF config from the extraction data (Game-of-Thrones data/*.csv) and game/config/rules.yaml.

  python scripts/gen_config.py [--data DIR] [--check]

Writes game/config/rom/{switches,coils,lights,settings,sounds,slides}.yaml and game/modes/<key>/config/<key>.yaml.
--check regenerates in memory and fails when a committed file differs (used by tests). The data directory is the
Game-of-Thrones repo's data/ (env GOT_DATA, default ../Game-of-Thrones/data); nothing is read from the ROM.
"""
import argparse
import json
import csv
import os
import re
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "game")
HEADER = "#config_version=6\n# GENERATED by scripts/gen_config.py - do not edit; change rules.yaml or the data tables.\n"
TRACK = {"tune": "music", "vo": "voice"}


def rows(data, name):
    with open(os.path.join(data, name), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def dump(obj):
    return HEADER + yaml.safe_dump(obj, sort_keys=False, default_flow_style=False, width=120, allow_unicode=True)


def good(name):
    return bool(name) and name != "invalid" and not name.isdigit() and "not_used" not in name and not name.startswith("_Z") \
        and "+" not in name and not name.startswith("dedicated_")


AUTOFIRE_SW = {"left_slingshot", "right_slingshot", "left_pop_bumper", "right_pop_bumper", "bottom_pop_bumper",
                "lock_1", "lock_2", "lock_3", "elevator_popper", "throne", "shooter_lane"}


def switches(data):
    out = {}
    nonpf = {15, 16, 17, 18, 19, 20, 21, 22, 23, 27, 45, 55}      # trough, start buttons, topper, dragon home
    for r in rows(data, "switches.csv"):
        n = int(r["sw_id"])
        if not good(r["name"]):
            continue
        sw = {"number": "S%d" % n, "label": r["label_en"].title() if r["label_en"] else r["name"]}
        tags = []
        if n == 45:
            tags.append("start")
        if n not in nonpf and r["name"] not in AUTOFIRE_SW:   # autofire devices tag these themselves
            tags.append("playfield_active")
        if tags:
            sw["tags"] = ", ".join(tags)
        out["s_" + r["name"]] = sw
    for r in rows(data, "switches_dedicated.csv"):
        if good(r["name"]):
            out["s_" + r["name"]] = {"number": "D%s" % r["idx"], "label": r["label_en"].title()}
    for name in ("service_back", "service_minus", "service_plus", "service_select"):
        out["s_" + name]["tags"] = "service"
    out["s_tilt_pendulum"]["tags"] = "tilt_warning"
    out["s_slam_tilt"]["tags"] = "slam_tilt"
    out["s_left_coin"]["tags"] = "left_coin"
    out["s_center_coin"]["tags"] = "center_coin"
    out["s_right_coin"]["tags"] = "right_coin"
    return {"switches": out}


def coils(data):
    out = {}
    for r in rows(data, "coils.csv"):
        if good(r["name"]):
            n = r["name"]
            out["c_" + n] = {"number": "C%s" % r["coil_id"], "label": r["label_en"].title(),
                             "default_pulse_ms": 25}      # CFG: Spike 1 coil timing not extracted (flags column is raw)
    for f in ("left_flipper_power", "right_flipper_power", "u_p_left_flipper", "u_p_right_flipper"):
        out["c_" + f]["default_hold_power"] = 0.25     # CFG: MPF needs a hold power to keep a flipper up (value not from ROM)
    out["c_shaker_motor"]["default_pulse_ms"] = 100
    return {"coils": out}


def lights(data):
    out = {}
    for r in rows(data, "lamps.csv"):
        n = r["name"]
        if n == "invalid":
            continue
        name = "l_lamp_%s" % n if n.isdigit() else "l_" + n
        out[name] = {"number": "L%s" % r["lamp_id"], "label": r["label_en"].title()}
    return {"lights": out}


def signed(v):
    v = int(v)
    return v - (1 << 32) if v >= (1 << 31) else v


def settings(data):
    out = {}
    for r in rows(data, "adjustments.csv"):
        if r["name"] == "ad_invalid":
            continue
        lo, hi, step, dflt = signed(r["min"]), signed(r["max"]), max(int(r["step"]), 1), signed(r["default"])
        vals = list(range(lo, hi + 1, step))
        if len(vals) > 40:                       # keep the menu usable: ~30 evenly spaced values plus the default
            keep = {vals[i * (len(vals) - 1) // 29] for i in range(30)} | {dflt}
            vals = sorted(keep)
        if dflt not in vals:
            vals = sorted(set(vals) | {dflt})
        labels = {0: "NO", 1: "YES"} if r["format"] == "adtml_no_yes" else {}
        out[r["name"]] = {"label": r["label_en"], "default": dflt, "key_type": "int", "sort": int(r["index"]),
                          "values": {v: labels.get(v, "{:,}".format(v)) + (" (default)" if v == dflt else "") for v in vals}}
    return {"settings": out}


def sounds(data, rules):
    """Core sound set only. The WAVs are copied by scripts/gen_media.py into game/sounds/<track>/ (gitignored)."""
    fx = {r["name"]: r for r in rows(data, "sound_effects.csv")}
    cat = {int(r["sound_id"]): r for r in rows(data, "audio_catalog.csv")}
    # GMC 1.0 (MPF 0.80) has no `sounds:`/`sound_pools:` section: it registers every file of game/sounds/<track>/ by
    # its file stem. A pooled effect plays its first sound (GMC has no random_force_next pool; CFG: lost variety).
    player, files = {}, {}
    for event, se in rules["sounds"].items():
        r = fx[se]
        i = int(r["sound_ids"].split()[0])
        c = cat[i]
        track = TRACK.get(c["category"], "sfx")
        stem = os.path.splitext(c["file"])[0]
        files[stem] = {"file": c["file"], "track": track}
        act = {"action": "play", "bus": track}
        if track == "music":
            act["loops"] = -1
        player["got_sound_" + event] = {stem: act}
    sounds.files = files
    return {"sound_player": player}


def slides(data, rules):
    """GMC slides are scenes (game/slides/vidNNN.tscn, one per DMD video); MPF only gets the slide_player."""
    player = {}
    for event, vid in rules["dmd"]["videos"].items():
        player[event] = {"vid%03d" % vid: {"expire": "2s"}}
    return {"slide_player": player}


SLIDE_TSCN = """[gd_scene load_steps=2 format=3]

[ext_resource type="Script" path="res://scripts/dmd_video.gd" id="1"]

[node name="MPFSlide" type="Control"]
layout_mode = 3
anchors_preset = 15
anchor_right = 1.0
anchor_bottom = 1.0
script = ExtResource("1")
video = "%s"
fps = %d
"""


def slide_scenes(rules):
    return {"slides/vid%03d.tscn" % v: SLIDE_TSCN % ("vid%03d" % v, rules["dmd"]["fps"])
            for v in sorted(set(rules["dmd"]["videos"].values()))}


HOUSE_CODE = {"winter_is_coming": "got.winter.WinterMode", "stark": "got.houses.StarkMode", "martell": "got.houses.MartellMode",
              "baratheon": "got.houses.BaratheonMode", "lannister": "got.houses.LannisterMode",
              "greyjoy": "got.houses.GreyjoyMode", "tyrell": "got.houses.TyrellMode", "targaryen": "got.houses.TargaryenMode"}
MB_CODE = {k: "got.multiballs.SetMultiball" for k in ("blackwater", "wall", "hand_of_the_king", "iron_throne")}
MB_CODE["winter_has_come"] = "got.multiballs.WinterHasComeMode"


def phase_switches(key):
    sys.path.insert(0, os.path.join(GAME))
    from got.phases import PHASES, RAM
    if key == "winter_has_come":
        from got.multiballs_data import WHC_SWITCHES
        return set(WHC_SWITCHES)
    ph = PHASES.get(key)
    if not ph:
        return set()
    out = {RAM, ph.get("super_switch", RAM)}
    for g in ph["groups"]:
        out |= set(g)
    return out


def mode_files(rules):
    out = {}
    d = rules["defaults"]
    for h in rules["houses"]:
        key = h["key"]
        award = {k: h["award"].get(k, 0) for k in ("start", "bump", "cap")}
        cfg = {"mode": {"start_events": "start_mode_" + key, "stop_events": "stop_mode_%s, ball_ending, tilt" % key,
                        "priority": 300, "game_mode": True,
                        "code": HOUSE_CODE.get(key, "got.award_mode.AwardMode")},
               "mode_settings": {"kind": "house", "id": h["id"], "key": key, "award": award, "shots": h["shots"],
                                 "shots_to_complete": d["house_shots_to_complete"], "hurry_up": bool(h.get("hurry_up")), "timer_s": h["timer_s"],
                                 "confidence": {"timer": h["timer_conf"], "award": h["award"]["conf"]}},
               "timers": {key + "_timer": {"start_value": h["timer_s"], "end_value": 0, "direction": "down",
                                           "tick_interval": "1s", "start_running": key != "winter_is_coming"}},
               "event_player": {"timer_%s_timer_complete" % key: "stop_mode_" + key}}
        out["%s/config/%s.yaml" % (key, key)] = cfg
    for m in rules["multiballs"]:
        key = m["key"]
        a = {k: m["jackpot"].get(k, 0) for k in ("start", "bump", "cap")}
        cfg = {"mode": {"start_events": "start_mode_" + key, "stop_events": "stop_mode_%s, multiball_%s_ended, tilt" % (key, key),
                        "priority": 400, "game_mode": True, "code": MB_CODE.get(key, "got.award_mode.AwardMode")},
               "mode_settings": {"kind": "multiball", "id": m["id"], "key": key, "award": a, "shots": sorted(set(m["jackpot_switches"]) | phase_switches(key)),
                                 "shots_to_complete": 0, "start_bonus": m["start_bonus"], "flag": m["flag"],
                                 "ball_save_adjustment": m["ball_save_adjustment"],
                                 "confidence": {"award": m["jackpot"]["conf"]}},
               "multiballs": {"mb_" + key: {"ball_count": d["multiball_balls"], "ball_count_type": "total",
                                           "shoot_again": "%ds" % m["ball_save_s"],
                                           "start_events": "mode_%s_started" % key}},
               "variable_player": {"mode_%s_started" % key: {"score": m["start_bonus"]}}}
        out["%s/config/%s.yaml" % (key, key)] = cfg
    return out


# award_id -> (house key | multiball key, "award"/"jackpot"/"super"): Game-of-Thrones data/scoring.csv (docs/07, H from ELF)
SCORING_MAP = {1: ("house", "targaryen"), 2: ("house", "stark"), 3: ("house", "baratheon"), 4: ("house", "lannister"),
               5: ("house", "greyjoy"), 6: ("house", "tyrell"), 7: ("house", "martell"), 17: ("house", "winter_is_coming"),
               8: ("mb", "blackwater", "jackpot"), 9: ("mb", "hand_of_the_king", "jackpot"), 10: ("mb", "midnight_madness", "jackpot"),
               11: ("mb", "wall", "jackpot"), 12: ("mb", "castle", "jackpot"), 13: ("mb", "castle", "super"),
               15: ("mb", "iron_throne", "jackpot"), 16: ("mb", "iron_throne", "super"), 18: ("mb", "winter_has_come", "jackpot")}


def apply_scoring(rules, data):
    """Override award start/bump/cap with the ELF values of data/scoring.csv where the table has them (blank = keep)."""
    byid = {int(r["award_id"]): r for r in rows(data, "scoring.csv")}
    houses = {h["key"]: h["award"] for h in rules["houses"]}
    mbs = {m["key"]: m for m in rules["multiballs"]}
    for aid, tgt in SCORING_MAP.items():
        r = byid.get(aid)
        if not r:
            continue
        a = houses[tgt[1]] if tgt[0] == "house" else mbs[tgt[1]].setdefault(tgt[2], {})
        for field, col in (("start", "elf_start"), ("bump", "elf_bump_increment"), ("cap", "elf_cap")):
            if r[col] != "":
                a[field] = int(r[col])
        a["conf"] = "H"
    # data/award_growth.csv fills what scoring.csv leaves blank (awards 1 and 9: docs/06 section d)
    for r in rows(data, "award_growth.csv"):
        tgt = SCORING_MAP.get(int(r["award_id"]))
        if not tgt:
            continue
        a = houses[tgt[1]] if tgt[0] == "house" else mbs[tgt[1]].setdefault(tgt[2], {})
        for field, col in (("start", "start_value"), ("bump", "increment_per_bump"), ("cap", "cap")):
            if r[col] != "" and not byid.get(int(r["award_id"]), {}).get({"start": "elf_start", "bump": "elf_bump_increment", "cap": "elf_cap"}[field]):
                a[field] = int(r[col])
    r19 = byid.get(19)
    if r19:
        rules["progression"]["castle_level_award"] = {"start": int(r19["elf_start"]), "bump": int(r19["elf_bump_increment"]),
                                                      "cap": int(r19["elf_cap"])}
    return rules


def switch_scores(data, rules):
    """Fixed switch scores: data/switch_events.csv base_points (docs/08, H) over the 03 s4 base scoring; pops 1,170 (traced live)."""
    pts = {}
    for r in rows(data, "switch_events.csv"):
        if r["kind"] == "node" and r["base_points"] and good(r["name"]):
            pts["s_" + r["name"]] = int(r["base_points"])
    for sw in ("s_left_pop_bumper", "s_right_pop_bumper", "s_bottom_pop_bumper"):
        pts[sw] = 1170
    for sw, v in rules["defaults"]["base_scoring"].items():
        if sw != "s_10_points":
            pts.setdefault(sw, v)
    return {"variable_player": {k + "_active": {"score": v} for k, v in sorted(pts.items())}}


def build(data):
    with open(os.path.join(GAME, "config", "rules.yaml"), encoding="utf-8") as f:
        rules = yaml.safe_load(f)
    rules = apply_scoring(rules, data)
    files = {}
    for name, fn in (("switches", switches), ("coils", coils), ("lights", lights), ("settings", settings)):
        files["config/rom/%s.yaml" % name] = dump(fn(data))
    sc = {"mode": {"start_events": "ball_starting", "stop_events": "ball_ending", "priority": 90, "game_mode": True}}
    sc.update(switch_scores(data, rules))
    files["modes/scoring/config/scoring.yaml"] = dump(sc)       # variable_player is only valid inside a game mode
    files["config/rom/sounds.yaml"] = dump(sounds(data, rules))
    files["config/rom/sound_files.json"] = json.dumps(sounds.files, indent=1, sort_keys=True) + "\n"
    files["config/rom/slides.yaml"] = dump(slides(data, rules))
    files.update(slide_scenes(rules))
    for rel, cfg in mode_files(rules).items():
        files["modes/" + rel] = dump(cfg)
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=os.environ.get("GOT_DATA", os.path.join(ROOT, "..", "Game-of-Thrones", "data")))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files, bad = build(a.data), []
    for rel, text in files.items():
        path = os.path.join(GAME, rel)
        if a.check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                bad.append(rel)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    if bad:
        print("out of date:", *bad, sep="\n  ")
        sys.exit(1)
    print(("checked" if a.check else "wrote"), len(files), "files")


if __name__ == "__main__":
    main()
