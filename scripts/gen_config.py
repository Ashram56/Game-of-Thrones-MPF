    path = os.path.join(data, "dmd_triggers.csv")
    if not os.path.exists(path):
        return {}, {}
    scenes, player = {}, {}
    romtext = dmd_text.rom_lines(data) if os.path.exists(os.path.join(data, "font_usage.csv")) else {}
    for r in rows(data, "dmd_triggers.csv"):
        if r["kind"] != "effect" or r["has_video"] != "no" or r["n_text_lines"] in ("", "0"):
            continue
        name = r["name"]
        if name in ("def_build_stark", "def_award_iron", "def_iron_tour_award", "def_hand_bg"):
            continue                                         # shown per character / castle / tour index below (data/dmd_table_layouts.csv)
        if name in romtext:                                  # ROM bitmap fonts and positions: PNG pages drawn by gen_media.py
            pages = romtext[name]
            slide = "tx_" + name[4:]
            if dmd_text.is_live(pages):                      # run-time values ({score}, {award}): drawn by dmd_text_live.gd
                body = TEXT_LIVE % json.dumps(pages, separators=(",", ":")).replace("\\", "\\\\").replace('"', '\\"')
