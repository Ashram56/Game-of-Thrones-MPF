#!/usr/bin/env python3
"""Start the game: Godot (GMC, BCP 5050) first, then MPF, optionally MPF Monitor. Standard library only.

  python3 scripts/run.py [--hw virtual] [--monitor] [--no-godot] [--text-ui] [--godot-wait S]
  python3 scripts/run.py --check          # can the game start? files, imports, no display, nothing left running

Environment (the names the platform images forward, MPF-Godot-Packaging common/games/README.md):
  GODOT            path of the Godot 4.5 executable (else `godot` on the PATH)
  MPF_GAME_VENV    folder of the Python environment with MPF (else ./.venv, else this Python)
  MPF_GAME_ARGS    extra Godot arguments of the board, for example "-- --rendering-driver opengl3" (appended as they are)
  DISPLAY          on Linux without one, Xvfb is started when it is installed

This script NEVER generates anything (media, config, Godot import): a bundle has the generated files but not their
inputs, and a launcher that regenerates empties the media there (MPF-Godot-Packaging platforms/game-bundles.md, rule 2).
Generation is scripts/setup.py's job, on the machine that builds the package.
"""
import argparse
import glob
import importlib
import json
import os
import shlex
import shutil
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "game")
EXE = ".exe" if os.name == "nt" else ""


def venv_bin(name):
    for folder in (os.environ.get("MPF_GAME_VENV"), os.path.join(ROOT, ".venv")):
        if folder:
            for sub in ("bin", "Scripts"):
                p = os.path.join(folder, sub, name + EXE)
                if os.path.exists(p):
                    return p
    return shutil.which(name) or ""


def python():
    for folder in (os.environ.get("MPF_GAME_VENV"), os.path.join(ROOT, ".venv")):
        if folder:
            for sub in ("bin", "Scripts"):
                p = os.path.join(folder, sub, "python" + EXE)
                if os.path.exists(p):
                    return p
    return sys.executable


def godot_path():
    p = os.environ.get("GODOT", "")
    if p and os.path.exists(p):
        return p
    found = sorted(glob.glob(os.path.join(ROOT, "tools", "godot", "Godot_v4.5*")))
    return found[0] if found else (shutil.which("godot") or "")


def package_problems():
    """What stops the game from starting: the generated files, the imports. Reads nothing outside the folder."""
    problems = []
    rom = os.path.join(GAME, "config", "rom")
    for name in ("switches.yaml", "coils.yaml", "lights.yaml", "settings.yaml", "sounds.yaml", "slides.yaml",
                 "sound_files.json", "pop_awards.json", "mystery_awards.csv", "swords.csv", "dmd_frames.json"):
        if not os.path.isfile(os.path.join(rom, name)):
            problems.append("game/config/rom/%s is missing (generated by scripts/setup.py)" % name)
    try:
        with open(os.path.join(rom, "sound_files.json"), encoding="utf-8") as f:
            sounds = json.load(f)
        gone = [s["file"] for s in sounds.values() if not os.path.isfile(os.path.join(GAME, "sounds", s["track"], s["file"]))]
        if gone:
            problems.append("%d of %d sounds are missing in game/sounds, first: %s (scripts/setup.py --assets DIR)"
                            % (len(gone), len(sounds), gone[0]))
    except (OSError, ValueError, KeyError):
        pass
    if not glob.glob(os.path.join(GAME, "images", "dmd_vid*_f000.png")):
        problems.append("no DMD frames in game/images (scripts/setup.py --assets DIR)")
    if not glob.glob(os.path.join(GAME, "slides", "*.tscn")):
        problems.append("game/slides has no scene")
    if not os.path.isdir(os.path.join(GAME, "addons", "mpf-gmc")):
        problems.append("game/addons/mpf-gmc is missing (the platform installs it: python -m mpf_godot addons game)")
    # every module the start chain and the MPF config reach: the game's code, imported the way MPF imports it
    sys.path.insert(0, GAME)
    for path in sorted(glob.glob(os.path.join(GAME, "got", "*.py"))):
        name = os.path.splitext(os.path.basename(path))[0]
        if name == "__init__":
            continue
        try:
            importlib.import_module("got." + name)
        except ImportError as e:
            if "mpf" in str(e):
                problems.append("MPF is not importable by this Python (%s): set MPF_GAME_VENV" % e)
                break
            problems.append("got.%s does not import: %s" % (name, e))
    return problems


def check():
    problems = package_problems()
    for p in problems:
        print("PROBLEM:", p)
    print("OK: the game can start" if not problems else "%d problem(s)" % len(problems))
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--hw", choices=("virtual",), default="virtual", help="hardware platform (virtual: MPF smart_virtual)")
    ap.add_argument("--monitor", action="store_true", help="also open MPF Monitor")
    ap.add_argument("--no-godot", action="store_true", help="MPF only (no display, no sound)")
    ap.add_argument("--text-ui", action="store_true", help="keep MPF's text UI (off by default: it needs a terminal)")
    ap.add_argument("--godot-wait", type=float, default=8.0, help="seconds between Godot and MPF (GMC listens on 5050; "
                    "probing the port makes GMC quit, so this waits instead of testing it)")
    ap.add_argument("--config", default="config,hw_virtual", help="MPF config files (default: config,hw_virtual)")
    ap.add_argument("--check", action="store_true", help="check that the game can start, then exit")
    a = ap.parse_args()
    if a.check or os.environ.get("MPF_BUNDLE_CHECK"):
        return check()
    problems = package_problems()
    if problems:
        print("The game cannot start:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    procs = []
    env = dict(os.environ)
    if sys.platform.startswith("linux") and not env.get("DISPLAY") and not env.get("WAYLAND_DISPLAY") and not a.no_godot:
        if shutil.which("Xvfb"):
            procs.append(subprocess.Popen(["Xvfb", ":99", "-screen", "0", "1024x256x24"], stdout=subprocess.DEVNULL,
                                          stderr=subprocess.DEVNULL))
            env["DISPLAY"] = ":99"
            time.sleep(2)
    try:
        if not a.no_godot:
            godot = godot_path()
            if not godot:
                print("Godot 4.5 not found: set GODOT, or use --no-godot", file=sys.stderr)
                return 1
            cmd = [godot, "--path", GAME] + shlex.split(env.get("MPF_GAME_ARGS", ""))
            procs.append(subprocess.Popen(cmd, env=env))
            time.sleep(a.godot_wait)
        mpf = venv_bin("mpf")
        if not mpf:
            print("mpf not found: set MPF_GAME_VENV to the Python environment with MPF 0.80.1", file=sys.stderr)
            return 1
        if a.monitor:
            mon = venv_bin("mpf-monitor")
            if mon:
                procs.append(subprocess.Popen([mon], env=env))
        cmd = [mpf, "game", GAME, "-c", a.config] + ([] if a.text_ui else ["-t"])
        return subprocess.call(cmd, cwd=GAME, env=env)
    finally:
        for p in reversed(procs):
            if p.poll() is None:
                p.terminate()


if __name__ == "__main__":
    sys.exit(main())
